@pytest.mark.parametrize("raw", [
    "PLAY ME, PIANO GIMHAE [플레이 미, 피아노 김해]",   # 대괄호 안이 한글 제목
    "연극 [더 드레서]",
    "제31회 김해분청도자기축제",                        # 회차·연도는 부제
    "2026 한밤의 유U;콘서트 12월",
    "판소리 그림자 인형극 <서천꽃밭 이야기>",            # 꺾쇠 제목
    "Play Me, 피아노 김해 게릴라 콘서트 (기묘한 봉리단길)",  # 괄호 안이 원제
    "Signature Concert ⅩI ‘Reverie’ with 드미트리 로카렌코프",  # 애매하면 그대로
    "사)한국가요작가협회 제1회 수로왕&허왕옥 가요제",
    "영도문화예술회관 Re:Start 시리즈, SAC on Screen 물의 정령",
    "Peak & Soak in 부산",
    "큰들 42주년 정기공연 [진주]".replace(" [진주]", ""),  # «정기공연»의 «공연»은 이름
    "남해탈공연박물관 상설공연",
    "상연",                                               # 꼬리만 있으면 그대로
    "[부산]",
    "두시 음악 살롱, 바로크의 정원 (11월)",              # 월은 회차(부제)
    "제49회 수요문화대학(제12강)",
    "제9회 진주국제재즈페스티벌 (12.05)",                 # 날짜 꼬리는 묶음 축제 구분에 쓰임
    "(오후7시)",
    "연극 [더 드레서] (앙코르)",
])
def test_keeps(raw):
    assert clean_title(raw) == (raw.strip(), [])


